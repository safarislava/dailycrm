use crate::endpoint;
use crate::middleware::admin_middleware::AdminMiddleware;
use crate::middleware::jwt_middleware::JwtMiddleware;
use crate::middleware::login_governor::login_governor;
use actix_governor::Governor;
use actix_web::web;

pub fn configure(config: &mut web::ServiceConfig) {
    config.service(
        web::scope("/api")
            .service(web::resource("/health").get(endpoint::health::get))
            .service(
                web::resource("/auth/login")
                    .wrap(Governor::new(&login_governor()))
                    .post(endpoint::auth::login::post),
            )
            .service(web::resource("/auth/refresh").post(endpoint::auth::refresh::post))
            .service(web::resource("/auth/logout").post(endpoint::auth::logout::post))
            .service(web::resource("/users").post(endpoint::users::create::create))
            .service(
                web::scope("/users/me")
                    .wrap(JwtMiddleware)
                    .service(web::resource("").get(endpoint::users::me::get))
                    .service(web::resource("/username").patch(endpoint::users::username::patch))
                    .service(web::resource("/password").patch(endpoint::users::password::patch))
                    .service(web::resource("/email").patch(endpoint::users::email::patch))
                    .service(web::resource("/roles").patch(endpoint::users::roles::patch))
                    .service(
                        web::resource("/notifications")
                            .patch(endpoint::users::notifications::patch),
                    ),
            )
            .service(
                web::scope("/admin")
                    .wrap(AdminMiddleware)
                    .wrap(JwtMiddleware)
                    .service(web::resource("/statistics").get(endpoint::admin::statistics::get))
                    .service(web::resource("/users").get(endpoint::admin::users::list::get))
                    .service(web::resource("/users/{user_id}/roles").patch(endpoint::admin::users::roles::patch))
                    .service(web::resource("/users/{user_id}").delete(endpoint::admin::users::delete::delete))
                    .service(
                        web::resource("/invitations")
                            .get(endpoint::admin::invitations::list::get)
                            .post(endpoint::admin::invitations::create::post),
                    )
                    .service(web::resource("/invitations/{token}").delete(endpoint::admin::invitations::delete::delete))
                    .service(web::resource("/logs").get(endpoint::admin::logs::get))
                    .service(web::resource("/digest").post(endpoint::admin::digest::post)),
            )
            .service(
                web::scope("")
                    .wrap(JwtMiddleware)
                    .service(web::resource("/invites").post(endpoint::invites::create::post))
                    .service(
                        web::scope("/projects")
                            .service(web::resource("/deadlines").get(endpoint::projects::deadlines::get::get))
                            .service(
                                web::resource("")
                                    .get(endpoint::projects::get::get)
                                    .post(endpoint::projects::create::create),
                            )
                            .service(
                                web::resource("/{project_id}")
                                    .delete(endpoint::projects::id::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/title")
                                    .patch(endpoint::projects::id::rename::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages")
                                    .get(endpoint::projects::id::stages::get::get)
                                    .post(endpoint::projects::id::stages::create::create),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}")
                                    .post(endpoint::projects::id::stages::position::create::create)
                                    .get(endpoint::projects::id::stages::position::get::get)
                                    .delete(endpoint::projects::id::stages::position::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/title")
                                    .patch(endpoint::projects::id::stages::position::title::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/position")
                                    .patch(endpoint::projects::id::stages::position::reorder::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/deadline")
                                    .patch(endpoint::projects::id::stages::position::deadline::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/advance-cost")
                                    .patch(endpoint::projects::id::stages::position::advance_cost::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/second-advance-cost")
                                    .patch(endpoint::projects::id::stages::position::second_advance_cost::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/final-cost")
                                    .patch(endpoint::projects::id::stages::position::final_cost::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/gip-confirmed")
                                    .patch(endpoint::projects::id::stages::position::gip_confirmed::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/advance-tranches")
                                    .post(endpoint::projects::id::stages::position::advance_tranches::post::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/advance-tranches/{tranche_id}")
                                    .delete(endpoint::projects::id::stages::position::advance_tranches::id::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/second-advance-tranches")
                                    .post(endpoint::projects::id::stages::position::second_advance_tranches::post::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/second-advance-tranches/{tranche_id}")
                                    .delete(endpoint::projects::id::stages::position::second_advance_tranches::id::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/final-tranches")
                                    .post(endpoint::projects::id::stages::position::final_tranches::post::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/final-tranches/{tranche_id}")
                                    .delete(endpoint::projects::id::stages::position::final_tranches::id::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/act")
                                    .get(endpoint::projects::id::stages::position::act::list::get)
                                    .post(endpoint::projects::id::stages::position::act::upload::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/act/{act_id}")
                                    .delete(endpoint::projects::id::stages::position::act::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/act/{act_id}/download")
                                    .get(endpoint::projects::id::stages::position::act::download::get),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/attachments")
                                    .get(endpoint::projects::id::stages::position::attachments::list::get)
                                    .post(endpoint::projects::id::stages::position::attachments::upload::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/attachments/{attachment_id}/download")
                                    .get(endpoint::projects::id::stages::position::attachments::download::get),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/attachments/{attachment_id}")
                                    .delete(endpoint::projects::id::stages::position::attachments::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/comments")
                                    .get(endpoint::projects::id::stages::position::comments::list::get)
                                    .post(endpoint::projects::id::stages::position::comments::create::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/comments/pinned")
                                    .get(endpoint::projects::id::stages::position::comments::pinned::get),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/comments/{comment_id}")
                                    .delete(endpoint::projects::id::stages::position::comments::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/comments/{comment_id}/pin")
                                    .patch(endpoint::projects::id::stages::position::comments::pin::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub")
                                    .post(endpoint::projects::id::stages::position::sub::create::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}")
                                    .get(endpoint::projects::id::stages::position::get::get)
                                    .delete(endpoint::projects::id::stages::position::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/title")
                                    .patch(endpoint::projects::id::stages::position::title::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/position")
                                    .patch(endpoint::projects::id::stages::position::reorder::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/deadline")
                                    .patch(endpoint::projects::id::stages::position::deadline::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/advance-cost")
                                    .patch(endpoint::projects::id::stages::position::advance_cost::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/second-advance-cost")
                                    .patch(endpoint::projects::id::stages::position::second_advance_cost::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/final-cost")
                                    .patch(endpoint::projects::id::stages::position::final_cost::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/gip-confirmed")
                                    .patch(endpoint::projects::id::stages::position::gip_confirmed::patch),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/advance-tranches")
                                    .post(endpoint::projects::id::stages::position::advance_tranches::post::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/advance-tranches/{tranche_id}")
                                    .delete(endpoint::projects::id::stages::position::advance_tranches::id::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/second-advance-tranches")
                                    .post(endpoint::projects::id::stages::position::second_advance_tranches::post::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/second-advance-tranches/{tranche_id}")
                                    .delete(endpoint::projects::id::stages::position::second_advance_tranches::id::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/final-tranches")
                                    .post(endpoint::projects::id::stages::position::final_tranches::post::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/final-tranches/{tranche_id}")
                                    .delete(endpoint::projects::id::stages::position::final_tranches::id::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/act")
                                    .get(endpoint::projects::id::stages::position::act::list::get)
                                    .post(endpoint::projects::id::stages::position::act::upload::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/act/{act_id}")
                                    .delete(endpoint::projects::id::stages::position::act::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/act/{act_id}/download")
                                    .get(endpoint::projects::id::stages::position::act::download::get),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/attachments")
                                    .get(endpoint::projects::id::stages::position::attachments::list::get)
                                    .post(endpoint::projects::id::stages::position::attachments::upload::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/attachments/{attachment_id}/download")
                                    .get(endpoint::projects::id::stages::position::attachments::download::get),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/attachments/{attachment_id}")
                                    .delete(endpoint::projects::id::stages::position::attachments::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/comments")
                                    .get(endpoint::projects::id::stages::position::comments::list::get)
                                    .post(endpoint::projects::id::stages::position::comments::create::post),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/comments/pinned")
                                    .get(endpoint::projects::id::stages::position::comments::pinned::get),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/comments/{comment_id}")
                                    .delete(endpoint::projects::id::stages::position::comments::delete::delete),
                            )
                            .service(
                                web::resource("/{project_id}/stages/{stage_id}/sub/{sub_id}/comments/{comment_id}/pin")
                                    .patch(endpoint::projects::id::stages::position::comments::pin::patch),
                            ),
                    ),
            ),
    );
}
